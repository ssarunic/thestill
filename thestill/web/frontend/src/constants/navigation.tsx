/** The entries a viewer sees: drops multi-user-only items in single-user mode. */
export function visibleNavItems(items: NavEntry[], isMultiUser: boolean): NavEntry[] {
  return isMultiUser ? items : items.filter((item) => !item.multiUserOnly)
}

