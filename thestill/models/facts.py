"""
Facts models for transcript cleaning.

Two-level facts architecture:
- PodcastFacts: Recurring knowledge (hosts, sponsors, keywords) - stable, user-editable
- EpisodeFacts: Episode-specific knowledge (guests, speaker mapping, topics)
"""

import re
from typing import Dict, FrozenSet, List

from pydantic import BaseModel, Field


class PodcastFacts(BaseModel):
    """
    Podcast-level facts that apply across all episodes.

    These facts are stable and only grow via user edits (no automatic accumulation).
    Stored as human-editable Markdown in data/podcast_facts/{slug}.facts.md
    """

    podcast_title: str
    hosts: List[str] = Field(default_factory=list)  # "Name - Description"
    recurring_roles: List[str] = Field(default_factory=list)  # "Ad Narrator - Reads sponsor segments"
    production_team: List[str] = Field(default_factory=list)  # "Dashiell Lewin - Research", "Becca Kinsel - Producer"
    known_guests: List[str] = Field(default_factory=list)  # "Name - Description"
    sponsors: List[str] = Field(default_factory=list)  # Sponsor/advertiser names
    keywords: List[str] = Field(default_factory=list)  # "Term (note about mishearing)"
    style_notes: List[str] = Field(default_factory=list)  # "British English preferred"


class EpisodeFacts(BaseModel):
    """
    Episode-specific facts extracted during Pass 1.

    Includes speaker mapping hypothesis generated by analyzing the transcript.
    Stored as Markdown in data/episode_facts/{podcast_slug}/{episode_slug}.facts.md
    """

    episode_title: str
    speaker_mapping: Dict[str, str] = Field(default_factory=dict)  # "SPEAKER_01": "Scott Galloway (Host)"
    guests: List[str] = Field(default_factory=list)  # "Name - Role/Description"
    topics_keywords: List[str] = Field(default_factory=list)  # Episode-specific topics
    ad_sponsors: List[str] = Field(default_factory=list)  # Sponsors mentioned in this episode


def strip_role_annotation(name: str) -> str:
    """Strip a trailing ``" (Role)"`` annotation from a speaker name.

    The facts file convention stores speaker names with an inline role
    — ``"Scott Galloway (Host)"`` — for editorial clarity. When the name
    is rendered into cleaned transcript output we want just ``"Scott
    Galloway"``. Only the *last* parenthesised block is stripped so a
    name like ``"A (B) (Host)"`` becomes ``"A (B)"``.
    """
    if " (" in name and name.endswith(")"):
        return name.rsplit(" (", 1)[0]
    return name


# Words that mark a speaker-mapping role or a guest bio as advertising —
# "Ad Narrator", "(Sponsor Read)", "Book Promo". Shared by the role
# linker (ad voices are never guests) and the segmented cleaner (ad
# voices are never conversation participants).
AD_WORD = r"(?:ads?|adverts?|advertisements?|advertising|sponsors?|sponsored|sponsorship|promos?|promotions?|promotional|commercials?)"
_AD_WORD_RE = re.compile(rf"\b{AD_WORD}\b", re.IGNORECASE)


def ad_voice_names(speaker_mapping: Dict[str, str]) -> FrozenSet[str]:
    """Rendered names of the speakers a mapping files as ad voices.

    A speaker is an ad voice when its role annotation or its name holds
    an ad word: ``"Ad Narrator 2"``, ``"Evan Gershkovich (Ad Narrator)"``.
    Names are returned as the cleaned transcript renders them (see
    ``strip_role_annotation``). A rendered name that another speaker
    carries without an ad role — ``"Lewis Goodall (Ad Narrator)"`` next
    to ``"Lewis Goodall (Host)"`` — is a participant and is left out.
    """
    ad: set = set()
    other: set = set()
    for name in speaker_mapping.values():
        if not name:
            continue
        rendered = strip_role_annotation(name).strip()
        role = name[len(rendered) :]
        (ad if _AD_WORD_RE.search(role) or _AD_WORD_RE.search(rendered) else other).add(rendered)
    return frozenset(ad - other)
